import { chromium } from "playwright";
const STATE = `${process.env.HOME}/skool-mcp/storageState.json`;
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ storageState: STATE, acceptDownloads: true });
const page = await ctx.newPage();
let clicked = false;
page.on("request", r => { const u = r.url(); if (clicked && !/ct\.skool|stripe|google|_next\/static|\.woff|\.svg/.test(u)) console.log("REQ:", r.method(), u.slice(0, 220)); });
ctx.on("page", async p => { console.log("POPUP:", p.url().slice(0, 220)); });
page.on("download", d => console.log("DOWNLOAD:", d.url().slice(0, 220), "->", d.suggestedFilename()));
await page.goto("https://www.skool.com/earlyaidopters/classroom/205bbe56?md=4a8f9c4f4b424bc48dc5a7a0bb78ce8d", { waitUntil: "domcontentloaded", timeout: 45000 });
await page.waitForTimeout(4000);
const span = page.locator("span", { hasText: "Transcript" }).first();
const box = await span.boundingBox();
console.log("span box:", JSON.stringify(box));
clicked = true;
if (box) { await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2); }
await page.waitForTimeout(5000);
console.log("pages now:", ctx.pages().length);
for (const p of ctx.pages()) console.log("  page:", p.url().slice(0, 180));
await browser.close();
